"""
Resource-Constrained List Scheduling and Lifetime Analysis.

Computes deterministic control step assignments and variable lifetimes for a DFG.

Invariant:
    Scheduling is NEVER modified for watermarking in V1.
    Watermarking occurs ONLY at register allocation.
"""

from typing import Dict, List, Tuple, Set, Optional, Any
from .dfg import DFG, DFGNode


class ScheduledDFG:
    """
    Holds the scheduled DFG control steps and variable lifetime intervals.
    """

    def __init__(
        self,
        dfg: DFG,
        node_step: Dict[int, int],
        total_steps: int,
        resource_config: Dict[str, int],
    ):
        self.dfg = dfg
        self.node_step = node_step
        self.total_steps = total_steps
        self.resource_config = resource_config
        self.step_nodes: Dict[int, List[int]] = {s: [] for s in range(total_steps)}
        for nid, s in node_step.items():
            self.step_nodes[s].append(nid)

        self.variable_lifetimes: Dict[str, Tuple[int, int]] = self._compute_lifetimes()
        self.live_vars_per_step: Dict[int, List[str]] = self._compute_live_vars_per_step()

    def _compute_lifetimes(self) -> Dict[str, Tuple[int, int]]:
        """
        Determines the [birth_step, death_step] interval for each variable.
        Input variables are born at step 0.
        Intermediate variables are born at the step of their generating operation.
        Variables die at the step of their last consuming operation.
        Outputs remain live until the final control step.
        """
        lifetimes: Dict[str, Tuple[int, int]] = {}
        all_vars = self.dfg.all_variables

        # 1. Determine birth step
        for v in all_vars:
            # Check if generated by a node
            producer = next((n for n in self.dfg.nodes if n.output == v), None)
            if producer is not None:
                birth = self.node_step[producer.node_id]
            else:
                birth = 0  # Primary input

            # 2. Determine death step
            consumers = [n for n in self.dfg.nodes if v in n.inputs]
            if consumers:
                death = max(self.node_step[n.node_id] for n in consumers)
            else:
                # Primary output or unconsumed variable
                death = self.total_steps - 1

            if death < birth:
                death = birth

            lifetimes[v] = (birth, death)

        return lifetimes

    def _compute_live_vars_per_step(self) -> Dict[int, List[str]]:
        live_map: Dict[int, List[str]] = {s: [] for s in range(self.total_steps)}
        for v, (birth, death) in self.variable_lifetimes.items():
            for s in range(birth, death + 1):
                if s < self.total_steps:
                    live_map[s].append(v)
        return live_map

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_steps": self.total_steps,
            "node_step": self.node_step,
            "variable_lifetimes": {v: list(span) for v, span in self.variable_lifetimes.items()},
            "live_vars_per_step": self.live_vars_per_step,
            "resource_config": self.resource_config,
        }


class ListScheduler:
    """
    Deterministic List Scheduler under resource constraints.
    """

    def __init__(self, resource_config: Optional[Dict[str, int]] = None):
        # Default: 2 adders, 2 multipliers, 2 sub, 2 others
        self.resource_config = resource_config or {"add": 2, "mul": 2, "sub": 2}

    def schedule(self, dfg: DFG) -> ScheduledDFG:
        """
        Schedules DFG operations into control steps adhering to dependencies and resource limits.
        """
        node_step: Dict[int, int] = {}
        scheduled_nodes: Set[int] = set()
        current_step = 0

        # Primary inputs ready at step 0
        produced_vars: Set[str] = set(dfg.inputs)

        while len(scheduled_nodes) < len(dfg.nodes):
            # Resources available in this step
            res_avail = dict(self.resource_config)

            # Find ready nodes whose inputs are all produced
            ready_nodes = []
            for n in dfg.nodes:
                if n.node_id not in scheduled_nodes:
                    if all(inp in produced_vars for inp in n.inputs):
                        ready_nodes.append(n)

            # Sort ready nodes deterministically by ID
            ready_nodes.sort(key=lambda n: n.node_id)

            step_scheduled = []
            for n in ready_nodes:
                op = n.op_type
                avail = res_avail.get(op, 999)  # unconstrained if not in config
                if avail > 0:
                    node_step[n.node_id] = current_step
                    step_scheduled.append(n)
                    res_avail[op] = avail - 1

            if not step_scheduled and len(scheduled_nodes) < len(dfg.nodes):
                # No node was scheduled due to resource starvation or cyclic dependency; advance step
                pass

            for n in step_scheduled:
                scheduled_nodes.add(n.node_id)
                produced_vars.add(n.output)

            current_step += 1

            if current_step > 500:
                raise RuntimeError("Scheduling exceeded 500 steps; possible cyclic dependency in DFG")

        total_steps = max(current_step, max(node_step.values()) + 1 if node_step else 1)
        return ScheduledDFG(dfg, node_step, total_steps, self.resource_config)
